/* ═══════════════════════════════════════════════════════════════════════════
   서버 시각 — 「언제가 지금인가」를 기기 시계에 묻지 않기 위한 아주 작은 모듈.

   ★ 왜 필요한가
     「잔량 정보가 오래됐다」는 판단은 **지금 시각**에 달려 있다. 그런데 치료실·병동에서
     쓰는 휴대폰 시계는 틀릴 수 있고, 몇 시간씩 어긋난 기기도 드물지 않다.
     기기 시계를 그대로 믿으면 멀쩡한 잔량에 「오래됐다」가 뜨거나, 반대로
     이틀 지난 잔량이 최신인 양 보인다.

   ★ 어떻게 하나 — 응답의 HTTP `Date` 헤더(= 서버가 찍은 시각)를 보고
     **기기 시계와의 차이(offset)만** 기억한다. 그 뒤로는
     `serverNow() = 기기시각 + offset` 으로 읽는다.
     ⓐ 시각을 통째로 들고 있지 않고 차이만 쓰므로, 받은 뒤 흐른 시간이 자연히 반영된다.
     ⓑ 기기 시계가 몇 시간 틀려 있어도 **흐름(60초가 60초인 것)** 은 맞으므로 안전하다.

   ★ Date 헤더는 **모든 HTTP 응답에 붙는다**(서버가 넣는다). 그래서 서버 코드를
     한 줄도 고치지 않고 쓸 수 있다. 혹시 읽히지 않으면(이상한 프록시·오래된 브라우저)
     offset 을 0 으로 두어 **기기 시각으로 떨어진다** — 기능이 멈추지는 않는다.

   ★ 시각 표시(fmtKst)와는 무관하다. 표시는 이미 KST 로 고정돼 있어
     기기의 시간대 설정과 상관없이 맞다. 여기서 다루는 것은 **「지금」** 뿐이다.
   ═══════════════════════════════════════════════════════════════════════════ */

/* 서버시각 − 기기시각(ms). null 이면 아직 모른다 = 기기 시각을 쓴다. */
let offset = null

/* fetch 응답의 Date 헤더를 넘긴다. 없거나 못 읽으면 조용히 무시한다
   (이전에 잡아 둔 offset 이 있으면 그대로 둔다 — 한 번 맞춘 것을 버릴 이유가 없다). */
export function noteServerDate(header) {
  const ms = Date.parse(String(header || ''))
  if (Number.isNaN(ms)) return false
  offset = ms - Date.now()
  return true
}

/* 지금(ms). 서버 기준이면 서버 기준, 아니면 기기 시각. */
export function serverNow() {
  return Date.now() + (offset || 0)
}

/* 서버 시각을 한 번이라도 잡았는지 — 시험과 진단용 */
export function hasServerTime() {
  return offset !== null
}

/* 시험 전용 — 모듈 상태를 비운다. 화면 코드에서는 부르지 않는다. */
export function resetServerClock() {
  offset = null
}
