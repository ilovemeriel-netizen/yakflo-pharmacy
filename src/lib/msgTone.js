/* 안내 띠의 색을 정하는 판정 — ★ 「실패를 초록으로 보여 주는 일」을 막는다.

   ★ 왜 — 지금까지는 `msg.includes('완료') ? 초록 : 빨강` 으로 색을 정했다.
     그래서 **실패 문구에 「완료」라는 글자가 들어 있으면 초록**이 됐다. 실제로 그런 문구가 있다:
       · 「가족 접종 완료 3명보다 적게 바꿀 수 없습니다」 (DB 거절 문구)
       · 「입고 완료! … · 단, 마스터 단가 변경 실패(…)」 (반만 성공)
     초록 띠는 사용자가 「저장됐다」고 읽는 신호다. 틀리면 안 바뀐 값을 바뀐 줄 알고 넘어간다.

   ★ 규칙 — **실패 낱말이 성공 낱말을 이긴다.** 둘 다 없으면 「알림」(파랑)이다.
   ★ 새 색을 만들지 않는다 — 기존 red / green / blue 토큰을 그대로 쓴다. */

/* 실패를 알리는 낱말. 하나라도 있으면 그 띠는 **빨강**이다. */
const BAD = /(실패|오류|못했|못 했|못합니다|없습니다|거절|풀렸|권한이 없|권한 없|불가|초과|중단|막혔|틀렸|빠짐|잘렸)/

/* 성공을 알리는 낱말 */
const GOOD = /(완료|성공|저장했|반영했|등록했|삭제했|바꿨|되돌렸|지웠)/

export function msgIsBad(msg) {
  return BAD.test(String(msg == null ? '' : msg))
}

/* ★ 실패 낱말이 하나라도 있으면 성공이 아니다 — 반만 성공한 것도 성공이 아니다. */
export function msgIsGood(msg) {
  const s = String(msg == null ? '' : msg)
  if (BAD.test(s)) return false
  return GOOD.test(s)
}
