-- ════════════════════════════════════════════════════════════════════════════
-- 0102 — 「확인번호 입력 제한 중에 신규로 접수된 건」을 표시한다.
--
-- ★ 왜 필요한가
--   확인번호를 여러 번 틀려 제한이 걸린 상태에서도 「본인의 신청 내역이 아닙니다」를
--   고르면 접수는 된다(막으면 진짜 다른 사람이 신청을 못 한다). 그 대신 **표시를 남겨**
--   관리자가 확인하게 한다. 표시가 없으면 우회 시도와 정상 동명이인이 구별되지 않는다.
--
-- ★ 칸만 더한다. 기본값이 거짓이라 기존 행·기존 동작은 그대로다.
-- ★ 개인정보가 아니다 — 참/거짓 하나다.
-- ════════════════════════════════════════════════════════════════════════════

alter table public.vaccine_survey_responses
  add column if not exists locked_bypass boolean not null default false;

comment on column public.vaccine_survey_responses.locked_bypass is
  '확인번호 입력 제한(잠금) 중에 「본인의 신청 내역이 아닙니다」로 접수된 건. '
  '관리 화면의 확인 사항에 「입력 제한 중 접수」로 뜬다. 접수를 막지는 않는다.';

notify pgrst, 'reload schema';
